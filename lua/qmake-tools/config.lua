---@class QMakeToolsConfig
local defaults = {
  -- Kits (Qt versions / toolchains). See README, e.g.:
  --   kits = {
  --     { name = "Qt 5.12 Desktop", qmake = "~/Qt/5.12.12/gcc_64/bin/qmake" },
  --     { name = "RPi", qmake = "/opt/qt5pi/bin/qmake", spec = "devices/linux-rasp-pi4-v3d-g++",
  --       path = { "/opt/cross/bin" }, run = false },
  --   }
  kits = {},
  -- Name of the kit for new configurations (nil = first kit)
  default_kit = nil,
  -- Automatically offer installed Qt versions as kits
  detect_kits = true,
  -- Deprecated, becomes the kit "Standard": fixed path to qmake
  qmake_executable = nil,
  -- make program for all kits (nil = matching the toolchain: make, on Windows
  -- mingw32-make or jom/nmake for MSVC)
  make_executable = nil,
  -- Name of the first configuration of a project
  default_config = "default",
  -- Build directory relative to the project root (or absolute).
  -- Placeholders: ${config}, ${kit}, ${build_type}, ${build_type_lower}
  build_dir = "build/${config}/${kit}-${build_type_lower}",
  build_types = { "Debug", "Release" },
  default_build_type = "Debug",
  -- Additional qmake arguments per build type and for all of them
  qmake_args = {},
  build_type_args = {
    Debug = { "CONFIG+=debug", "CONFIG+=qml_debug" },
    Release = { "CONFIG+=release" },
  },
  -- Parallel jobs for make (nil = number of CPU cores)
  jobs = nil,
  -- "auto" | "compiledb" | "builtin" | "bear" | false
  --   compiledb: evaluates `make -n`, very fast, no build needed (GNU make only)
  --   builtin:   reads the Makefiles generated by qmake directly, without an extra program;
  --              also works with nmake/jom (MSVC)
  --   bear:      records during the actual build (more accurate, but only after the build)
  --   auto:      compiledb if installed and GNU make, otherwise builtin
  compile_commands = "auto",
  -- Link compile_commands.json into the project root (for clangd)
  link_compile_commands = true,
  -- Restart clangd automatically after Generate
  restart_clangd = true,
  -- Regenerate automatically when saving .pro/.pri
  regenerate_on_save = true,
  -- Build automatically before :QMakeRun
  build_before_run = true,
  -- Like Qt Creator ("Add build library search path to LD_LIBRARY_PATH"):
  -- prepend -L directories from LIBS, shared libraries built in the project, and the
  -- Qt lib directory to LD_LIBRARY_PATH at startup
  -- (on Windows to PATH, where Windows looks for DLLs)
  add_library_search_paths = true,
  -- Executor window with the live output of qmake/compiledb/make
  executor = {
    enabled = true,
    open = "always",          -- "always" | "on_error" | "never" (then only via :QMakeOpenExecutor)
    position = "bottom",      -- "bottom" | "top" | "right" | "left"
    size = 15,                -- height or width for right/left
    focus = false,            -- jump into it when opening
    wrap = false,
    close_on_success = false, -- close automatically after a successful run
    close_on_success_delay = 1500,
  },
  -- Quickfix window: "always" | "on_error" | "never"
  -- The quickfix list is always filled (:cnext/:cprev work),
  -- only the window stays closed because the executor already shows the output.
  open_quickfix = "never",
  -- errorformat for the quickfix list (nil = built-in: gcc/clang, MSVC, qmake,
  -- directory changes from make/mingw32-make)
  errorformat = nil,
  -- Height of the terminal split for :QMakeRun
  terminal_height = 15,
}

local M = { options = vim.deepcopy(defaults) }

function M.setup(opts)
  M.options = vim.tbl_deep_extend("force", vim.deepcopy(defaults), opts or {})
end

return M
